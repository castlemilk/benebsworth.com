// @vitest-environment jsdom
import React from 'react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { renderToString } from 'react-dom/server'
import { GenerativeGallery } from './gallery'
import { STUDIES } from '@/lib/generative-svg/model'
import { renderStudySvg } from '@/lib/generative-svg/render'

const writeText = vi.fn<(_text: string) => Promise<void>>()
const selected = () => screen.getByRole('region', { name: 'Selected study' })
const download = () => within(selected()).getByRole('link', { name: 'Download SVG' }) as HTMLAnchorElement
const source = () => decodeURIComponent(download().getAttribute('href')!.split(',').slice(1).join(','))
const geometry = (svg: string) => [...new DOMParser().parseFromString(svg, 'image/svg+xml').querySelectorAll('polyline,polygon,circle,text')].map(n => ['points','cx','cy','r','x','y'].map(a => n.getAttribute(a)))
beforeEach(() => {
  writeText.mockReset().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
})
afterEach(() => { cleanup(); vi.restoreAllMocks() })

describe('generative SVG gallery', () => {
  it('renders all 25 real studies and a usable server-rendered default export', () => {
    const html = renderToString(<GenerativeGallery />)
    expect(html).toContain('Drawing with')
    expect(html).toContain('data:image/svg+xml')
    expect(html).not.toContain('BrandBrain')
    render(<GenerativeGallery />)
    expect(screen.getAllByRole('button', { name: /^Open / })).toHaveLength(25)
    expect(source()).toBe(renderStudySvg(STUDIES[0]))
  })
  it.each(['Mathematics', 'Physics', 'Algorithms', 'Distributed systems', 'Electronics'])('opens and exports every %s study with retained custom appearance', category => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Style preset'), { target: { value: 'technical' } })
    fireEvent.change(screen.getByLabelText('Subject'), { target: { value: category } })
    expect(screen.getAllByRole('button', { name: /^Open / })).toHaveLength(5)
    for (const study of STUDIES.filter(s => s.category === category)) {
      fireEvent.click(screen.getByRole('button', { name: `Open ${study.title}` }))
      for (const parameter of study.parameters) fireEvent.change(screen.getByLabelText(parameter.label), { target: { value: String(parameter.max) } })
      const recipe = JSON.parse(new DOMParser().parseFromString(source(), 'image/svg+xml').querySelector('metadata')!.textContent!)
      expect(recipe.study).toBe(study.id)
      expect(recipe.parameters).toEqual(Object.fromEntries(study.parameters.map(p => [p.key, p.max])))
      expect(source()).toContain('stroke-linecap="butt"')
      expect(download().getAttribute('download')).toBe(`${study.id}.svg`)
    }
  })
  it('changes all drawing appearances while preserving the selected model coordinates', () => {
    render(<GenerativeGallery />)
    const before = geometry(source())
    fireEvent.change(screen.getByLabelText('Preview surface'), { target: { value: 'dark' } })
    fireEvent.change(screen.getByLabelText('Line weight'), { target: { value: '3.7' } })
    expect(source()).toContain('#f4f1e8')
    expect(source()).toContain('stroke-width="3.7"')
    expect(geometry(source())).toEqual(before)
    fireEvent.change(screen.getByLabelText('Ink'), { target: { value: 'monochrome' } })
    expect(source()).not.toContain('#ffaaa5')
    expect(geometry(source())).toEqual(before)
    fireEvent.click(screen.getByRole('button', { name: 'Reset appearance' }))
    expect(source()).toBe(renderStudySvg(STUDIES[0]))
  })
  it('keeps mathematical parameters distinct from appearance reset', () => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Amplitude'), { target: { value: '0.4' } })
    fireEvent.change(screen.getByLabelText('Cycles'), { target: { value: '4' } })
    const changed = source()
    expect(changed).toBe(renderStudySvg(STUDIES[0], { amplitude: 0.4, cycles: 4 }))
    fireEvent.click(screen.getByRole('button', { name: 'Reset appearance' }))
    expect(source()).toBe(changed)
    fireEvent.click(screen.getByRole('button', { name: 'Reset parameters' }))
    expect(source()).toBe(renderStudySvg(STUDIES[0]))
  })
  it('opens a graph, retains appearance and gives keyboard focus to the workbench', () => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Preview surface'), { target: { value: 'dark' } })
    fireEvent.click(screen.getByRole('button', { name: 'Open Binary search tree' }))
    expect(document.activeElement).toBe(selected())
    expect(within(selected()).getByRole('heading', { name: 'Binary search tree' })).toBeTruthy()
    fireEvent.change(screen.getByLabelText('Find key'), { target: { value: '7' } })
    expect(source()).toBe(renderStudySvg(STUDIES[4], { target: 7 }, { theme: 'dark' }))
    expect(download().getAttribute('download')).toBe('binary-search-tree.svg')
  })
  it('labels the prism honestly and does not invent physical parameter controls', () => {
    render(<GenerativeGallery />)
    fireEvent.click(screen.getByRole('button', { name: 'Open Prism study' }))
    expect(within(selected()).getByText(/not computed with Snell/, { selector: 'p' })).toBeTruthy()
    expect(within(selected()).queryByRole('group', { name: 'Parameters' })).toBeNull()
    expect(source()).toContain('Provenance: illustrative')
  })
  it('filters by name and subject, then recovers an empty result with focus restored', () => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Subject'), { target: { value: 'Mathematics' } })
    expect(screen.getAllByRole('button', { name: /^Open / })).toHaveLength(5)
    fireEvent.change(screen.getByLabelText('Find a study'), { target: { value: 'prism' } })
    expect(screen.getByRole('heading', { name: 'No matching studies' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Show all studies' }))
    expect(document.activeElement).toBe(screen.getByLabelText('Find a study'))
    expect(screen.getAllByRole('button', { name: /^Open / })).toHaveLength(25)
  })
  it('copies exactly the current transparent download bytes, with truthful rejection and retry', async () => {
    writeText.mockRejectedValueOnce(new Error('Permission denied'))
    render(<GenerativeGallery />)
    const expected = source()
    fireEvent.click(screen.getByRole('button', { name: 'Copy SVG' }))
    await act(async () => {})
    expect(writeText).toHaveBeenCalledExactlyOnceWith(expected)
    expect(within(selected()).getByRole('status', { name: 'SVG export status' }).textContent).toContain('Clipboard unavailable')
    fireEvent.click(screen.getByRole('button', { name: 'Retry copy' }))
    await act(async () => {})
    expect(screen.getByRole('button', { name: 'SVG copied' })).toBeTruthy()
    expect(source()).not.toContain('<rect')
  })
  it('does not transfer old copy success into a changed model or palette', async () => {
    let resolve!: () => void
    writeText.mockReturnValue(new Promise<void>(r => { resolve = r }))
    render(<GenerativeGallery />)
    fireEvent.click(screen.getByRole('button', { name: 'Copy SVG' }))
    await act(async () => {})
    fireEvent.change(screen.getByLabelText('Amplitude'), { target: { value: '0.6' } })
    await act(async () => resolve())
    expect(screen.getByRole('button', { name: 'Copy SVG' })).toBeTruthy()
    expect(within(selected()).getByRole('status', { name: 'SVG export status' }).textContent).toBe('')
  })
  it('removes construction lines without changing measured strokes', () => {
    render(<GenerativeGallery />)
    const initial = geometry(source())
    fireEvent.click(screen.getByLabelText('Construction lines'))
    expect(geometry(source())).toEqual(initial.slice(2))
    fireEvent.click(screen.getByLabelText('Construction lines'))
    expect(geometry(source())).toEqual(initial)
  })
  it('retains zero-vector data and distinguishes monochrome tree searches', () => {
    render(<GenerativeGallery />)
    fireEvent.click(screen.getByRole('button', { name: 'Open Rotational field' }))
    const field = source()
    fireEvent.click(screen.getByLabelText('Construction lines'))
    expect(geometry(source())).toEqual(geometry(field))
    fireEvent.change(screen.getByLabelText('Ink'), { target: { value: 'monochrome' } })
    fireEvent.click(screen.getByRole('button', { name: 'Open Binary search tree' }))
    const left = source()
    fireEvent.change(screen.getByLabelText('Find key'), { target: { value: '7' } })
    expect(geometry(source())).toEqual(geometry(left))
    const strokes = (svg: string) => [...new DOMParser().parseFromString(svg, 'image/svg+xml').querySelectorAll('polyline')].map(n => n.getAttribute('stroke-width'))
    expect(strokes(source())).not.toEqual(strokes(left))
    expect(source()).not.toContain('Red follows')
  })
  it('tunes custom inks and stroke settings, embeds them in exports and resets appearance only', () => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Amplitude'), { target: { value: '0.4' } })
    const before = geometry(source())
    fireEvent.change(screen.getByLabelText('Style preset'), { target: { value: 'technical' } })
    expect(source()).toContain('stroke-linecap="butt"')
    expect((screen.getByLabelText('Amplitude') as HTMLInputElement).value).toBe('0.4')
    fireEvent.change(screen.getByLabelText('Ink'), { target: { value: 'custom' } })
    fireEvent.change(screen.getByLabelText('Drawing ink'), { target: { value: '#123456' } })
    fireEvent.change(screen.getByLabelText('Accent ink'), { target: { value: '#654321' } })
    fireEvent.change(screen.getByLabelText('Guide opacity'), { target: { value: '0.3' } })
    fireEvent.change(screen.getByLabelText('Selection emphasis'), { target: { value: '1.9' } })
    expect((screen.getByLabelText('Style preset') as HTMLSelectElement).value).toBe('custom')
    expect(source()).toContain('#123456')
    expect(source()).toContain('#654321')
    expect(source()).toContain('stroke-opacity="0.3"')
    const recipe = JSON.parse(new DOMParser().parseFromString(source(), 'image/svg+xml').querySelector('metadata')!.textContent!)
    expect(recipe.appearance).toMatchObject({ inkColor: '#123456', accentColor: '#654321', guideOpacity: 0.3, emphasis: 1.9 })
    expect(geometry(source())).toEqual(before)
    fireEvent.change(screen.getByLabelText('Preview surface'), { target: { value: 'dark' } })
    expect(source()).toContain('#123456')
    expect(screen.getByRole('status', { name: 'Ink contrast' }).textContent).toContain('Low contrast')
    fireEvent.click(screen.getByRole('button', { name: 'Reset appearance' }))
    expect((screen.getByLabelText('Amplitude') as HTMLInputElement).value).toBe('0.4')
    expect((screen.getByLabelText('Style preset') as HTMLSelectElement).value).toBe('folio')
  })
  it('retains each study tuning when browsing and resets only the selected parameters', () => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Amplitude'), { target: { value: '0.4' } })
    fireEvent.change(screen.getByLabelText('Style preset'), { target: { value: 'bold' } })
    fireEvent.click(screen.getByRole('button', { name: 'Open QAM constellation' }))
    fireEvent.change(screen.getByLabelText('Bits per axis'), { target: { value: '3' } })
    expect(source()).toContain('qam-constellation')
    fireEvent.click(screen.getByRole('button', { name: 'Open Sine wave' }))
    expect((screen.getByLabelText('Amplitude') as HTMLInputElement).value).toBe('0.4')
    fireEvent.click(screen.getByRole('button', { name: 'Reset parameters' }))
    expect((screen.getByLabelText('Style preset') as HTMLSelectElement).value).toBe('bold')
    fireEvent.click(screen.getByRole('button', { name: 'Open QAM constellation' }))
    expect((screen.getByLabelText('Bits per axis') as HTMLInputElement).value).toBe('3')
    fireEvent.change(screen.getByLabelText('Subject'), { target: { value: 'Electronics' } })
    expect(screen.getAllByRole('button', { name: /^Open / })).toHaveLength(5)
  })
  it('copies exactly the custom lab export and disables hidden-guide tuning', async () => {
    render(<GenerativeGallery />)
    fireEvent.change(screen.getByLabelText('Ink'), { target: { value: 'custom' } })
    fireEvent.change(screen.getByLabelText('Drawing ink'), { target: { value: '#f4f1e8' } })
    expect(screen.getByRole('status', { name: 'Ink contrast' }).textContent).toContain('Low contrast')
    fireEvent.click(screen.getByLabelText('Construction lines'))
    expect((screen.getByLabelText('Guide opacity') as HTMLInputElement).disabled).toBe(true)
    const expected = source()
    fireEvent.click(screen.getByRole('button', { name: 'Copy SVG' }))
    await act(async () => {})
    expect(writeText).toHaveBeenCalledExactlyOnceWith(expected)
  })
  it('does not retain copy success when switching between studies with equal parameter shapes', async () => {
    render(<GenerativeGallery />)
    fireEvent.click(screen.getByRole('button', { name: 'Open Rotational field' }))
    fireEvent.click(screen.getByRole('button', { name: 'Copy SVG' }))
    await act(async () => {})
    expect(screen.getByRole('button', { name: 'SVG copied' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Open Prism study' }))
    expect(screen.getByRole('button', { name: 'Copy SVG' })).toBeTruthy()
    expect(within(selected()).getByRole('status', { name: 'SVG export status' }).textContent).toBe('')
  })

})
