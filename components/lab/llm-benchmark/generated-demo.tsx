'use client'

import { useEffect, useMemo, useState } from 'react'
import { BENCHMARK_MODELS, getModel, resultsForTask } from '@/lib/lab/llm-benchmark/registry'
import type { BenchmarkTask } from '@/lib/lab/llm-benchmark/types'
import { cn } from '@/lib/utils'
import { Monitor, FileCode, AlertCircle, CheckCircle2, XCircle, Play } from 'lucide-react'

interface GeneratedDemoProps {
  task: BenchmarkTask
  className?: string
}

const HTML_CATEGORIES = new Set([
  '3d-physics-animation',
  'advanced-game-building',
  'advanced-physics',
  'advanced-electronics',
  'ui-building',
])

function isHtmlRunnable(task: BenchmarkTask): boolean {
  return HTML_CATEGORIES.has(task.category)
}

function useBlobUrl(output: string | undefined): string | undefined {
  return useMemo(() => {
    if (!output) return undefined
    const blob = new Blob([output], { type: 'text/html' })
    return URL.createObjectURL(blob)
  }, [output])
}

export function GeneratedDemo({ task, className = '' }: GeneratedDemoProps) {
  const [selectedModelId, setSelectedModelId] = useState<string>(BENCHMARK_MODELS[0]?.id ?? '')
  const [isClient, setIsClient] = useState(false)

  useEffect(() => {
    setIsClient(true)
  }, [])

  const results = useMemo(() => resultsForTask(task.id), [task.id])
  const byModel = useMemo(() => new Map(results.map((r) => [r.modelId, r])), [results])

  const selectedResult = byModel.get(selectedModelId)
  const selectedModel = getModel(selectedModelId)
  const blobUrl = useBlobUrl(selectedResult?.output)

  const runnable = isHtmlRunnable(task)
  const hasOutput = Boolean(selectedResult?.output && selectedResult.output.trim().length > 0)
  const isSuccess = selectedResult?.status === 'success'

  return (
    <div className={cn('overflow-hidden rounded-xl border border-[var(--color-border)] bg-[var(--color-surface)]', className)}>
      <div className="border-b border-[var(--color-border)] bg-[var(--color-surface-2)] px-5 py-3">
        <div className="flex items-center gap-2 font-mono text-xs uppercase tracking-wider text-muted">
          <Monitor className="h-4 w-4" aria-hidden />
          Generated demo
        </div>
        <p className="mt-1 text-sm text-fg/60">
          Render the artifact a model actually produced for “{task.title}”.
        </p>
      </div>

      <div className="border-b border-[var(--color-border)] bg-[var(--color-surface)] px-4 py-3">
        <div className="flex flex-wrap items-center gap-3">
          <select
            aria-label="Model for generated demo"
            value={selectedModelId}
            onChange={(e) => setSelectedModelId(e.target.value)}
            className="block rounded-lg border border-[var(--color-border)] bg-[var(--color-bg)] px-3 py-2 text-sm font-medium outline-none focus:ring-2 focus:ring-[var(--color-project)]"
          >
            {BENCHMARK_MODELS.map((m) => (
              <option key={m.id} value={m.id}>
                {m.name}
              </option>
            ))}
          </select>

          {selectedResult && (
            <span
              className={cn(
                'inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-xs font-medium',
                isSuccess
                  ? 'border-emerald-500/20 bg-emerald-500/10 text-emerald-600 dark:text-emerald-400'
                  : 'border-red-500/20 bg-red-500/10 text-red-600 dark:text-red-400'
              )}
            >
              {isSuccess ? <CheckCircle2 className="h-3.5 w-3.5" /> : <XCircle className="h-3.5 w-3.5" />}
              {selectedResult.score.toFixed(1)}
            </span>
          )}
        </div>
      </div>

      <div className="relative bg-[var(--color-bg)]">
        {!hasOutput ? (
          <div className="flex min-h-[320px] flex-col items-center justify-center p-8 text-center">
            <AlertCircle className="h-8 w-8 text-muted" aria-hidden />
            <p className="mt-3 text-sm text-fg/70">No generated output for {selectedModel?.name ?? selectedModelId} yet.</p>
            <p className="mt-1 max-w-xs text-xs text-muted">
              Run the harness for this model to capture a live artifact.
            </p>
          </div>
        ) : runnable ? (
          <>
            {!isClient ? (
              <div className="flex min-h-[320px] items-center justify-center">
                <p className="text-sm text-muted">Loading demo…</p>
              </div>
            ) : (
              <iframe
                src={blobUrl}
                title={`${task.title} generated by ${selectedModel?.name ?? selectedModelId}`}
                className="h-[420px] w-full border-0 md:h-[520px]"
                sandbox="allow-scripts allow-same-origin"
              />
            )}
          </>
        ) : (
          <div className="flex min-h-[320px] flex-col">
            <div className="flex items-center gap-2 border-b border-[var(--color-border)] bg-[var(--color-surface)] px-4 py-2 font-mono text-xs text-muted">
              <FileCode className="h-3.5 w-3.5" aria-hidden />
              Generated output
            </div>
            <pre className="flex-1 overflow-auto p-4 font-mono text-xs leading-relaxed">
              <code>{selectedResult?.output}</code>
            </pre>
          </div>
        )}
      </div>

      {blobUrl && <RevokeBlob url={blobUrl} />}
    </div>
  )
}

function RevokeBlob({ url }: { url: string }) {
  useEffect(() => () => URL.revokeObjectURL(url), [url])
  return null
}
