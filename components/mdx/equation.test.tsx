// @vitest-environment jsdom
import React from 'react'
import { readFileSync } from 'node:fs'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render } from '@testing-library/react'
import { Equation } from './equation'

const source = '  \\Gamma = \\frac{Z_L - Z_0}{Z_L + Z_0}  '
const writeText = vi.fn()
const execCommand = vi.fn()
function setup() {
  const view = render(<Equation id="eqn:exact" number="3.2" caption={<em>Exact caption</em>} latex={source}><span>Rendered children, not the copy source</span></Equation>)
  const trigger = view.getByRole('button', { name: 'Copy equation to clipboard' })
  function open() {
    act(() => trigger.focus())
    fireEvent.click(trigger)
    act(() => vi.advanceTimersByTime(20))
  }
  open()
  return { ...view, trigger, open }
}
beforeEach(() => {
  vi.useFakeTimers()
  writeText.mockReset().mockResolvedValue(undefined)
  execCommand.mockReset().mockReturnValue(true)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  Object.defineProperty(document, 'execCommand', { configurable: true, value: execCommand })
})
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks() })

describe('Equation canonical Gamma action menu', () => {
  it('preserves anchors, optional metadata and children without adding source controls', () => {
    const { container, queryByRole, getByRole } = render(<Equation id="eqn:original"><strong>Display only</strong></Equation>)
    expect(container.querySelector('figure')?.id).toBe('eqn:original')
    expect(container.querySelector('figcaption')).toBeNull()
    expect(getByRole('region', { name: 'Equation' }).textContent).toBe('Display only')
    expect(queryByRole('button')).toBeNull()
    expect(queryByRole('status')).toBeNull()
  })
  it('uses the maintained menu with exact metadata, labels and no fictitious shortcut', () => {
    const { trigger, getByRole, queryByRole, container } = setup()
    expect(trigger.classList.contains('action-menu-trigger')).toBe(true)
    expect(trigger.getAttribute('aria-haspopup')).toBe('menu')
    expect(getByRole('menu').id).toBe(trigger.getAttribute('aria-controls'))
    expect(getByRole('region', { name: 'Equation (3.2)' }).getAttribute('aria-describedby')).toBe(container.querySelector('figcaption')?.id)
    expect(container.querySelector('figcaption')?.textContent).toBe('(3.2)Exact caption')
    expect(container.querySelector('kbd')).toBeNull()
    fireEvent.click(trigger)
    expect(trigger.getAttribute('aria-expanded')).toBe('false')
    expect(queryByRole('menu')).toBeNull()
    expect(queryByRole('menuitem')).toBeNull()
  })
  it.each(['Escape', 'Tab'])('follows ArrowDown/Home/End/arrows and closes with %s restoring trigger focus', key => {
    const { getByRole, trigger, queryByRole } = setup()
    fireEvent.keyDown(getByRole('menu'), { key: 'Escape' })
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    act(() => vi.advanceTimersByTime(20))
    const first = getByRole('menuitem', { name: /Copy LaTeX/ })
    const last = getByRole('menuitem', { name: /Copy math/ })
    expect(document.activeElement).toBe(first)
    fireEvent.keyDown(first, { key: 'End' })
    expect(document.activeElement).toBe(last)
    fireEvent.keyDown(last, { key: 'Home' })
    expect(document.activeElement).toBe(first)
    fireEvent.keyDown(first, { key: 'ArrowDown' })
    expect(document.activeElement).toBe(last)
    fireEvent.keyDown(last, { key: 'ArrowUp' })
    expect(document.activeElement).toBe(first)
    fireEvent.keyDown(first, { key })
    expect(queryByRole('menu')).toBeNull()
    expect(document.activeElement).toBe(trigger)
  })
  it.each([['Copy LaTeX', `$$\n${source.trim()}\n$$`], ['Copy math', source.trim()]])('copies exact %s payload, closes, focuses trigger and keeps feedback outside the menu', async (label, payload) => {
    const { getByRole, trigger, queryByRole } = setup()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: new RegExp(label) })))
    expect(writeText).toHaveBeenCalledWith(payload)
    expect(queryByRole('menu')).toBeNull()
    expect(document.activeElement).toBe(trigger)
    expect(getByRole('status').textContent).toBe('Copied')
    act(() => vi.advanceTimersByTime(1500))
    expect(getByRole('status').textContent).toBe('')
    expect(document.activeElement).toBe(trigger)
  })
  it.each(['rejected', 'missing'])('uses truthful fallback for %s clipboard and restores focus/selection', async condition => {
    if (condition === 'missing') Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined })
    else writeText.mockRejectedValue(new Error('Denied'))
    const { getByRole, container, trigger } = setup()
    const range = document.createRange()
    range.selectNodeContents(container.querySelector('.equation-math')!)
    window.getSelection()?.removeAllRanges()
    window.getSelection()?.addRange(range)
    vi.spyOn(HTMLTextAreaElement.prototype, 'select').mockImplementation(function (this: HTMLTextAreaElement) { this.focus() })
    execCommand.mockImplementation(() => {
      expect(document.activeElement).toBe(document.querySelector('textarea'))
      expect(document.querySelector('textarea')?.value).toBe(source.trim())
      return true
    })
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(execCommand).toHaveBeenCalledWith('copy')
    expect(document.querySelector('textarea')).toBeNull()
    expect(document.activeElement).toBe(trigger)
    expect(window.getSelection()?.toString()).toBe('Rendered children, not the copy source')
    expect(getByRole('status').textContent).toBe('Copied')
    window.getSelection()?.removeAllRanges()
  })
  it.each(['false', 'throws', 'missing'])('reports persistent error when fallback %s and permits retry', async failure => {
    writeText.mockRejectedValue(new Error('Denied'))
    if (failure === 'throws') execCommand.mockImplementation(() => { throw new Error('Denied') })
    else if (failure === 'missing') Object.defineProperty(document, 'execCommand', { configurable: true, value: undefined })
    else execCommand.mockReturnValue(false)
    const { getByRole, trigger, open } = setup()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(getByRole('status').textContent).toContain('Copy unavailable')
    expect(getByRole('status').textContent).not.toContain('Copied')
    expect(document.querySelector('textarea')).toBeNull()
    expect(document.activeElement).toBe(trigger)
    act(() => vi.advanceTimersByTime(2000))
    expect(getByRole('status').textContent).toContain('Copy unavailable')
    writeText.mockResolvedValue(undefined)
    open()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(getByRole('status').textContent).toBe('Copied')
  })
  it('closes on outside pointerdown without changing math', () => {
    const { getByRole, queryByRole } = setup()
    fireEvent.pointerDown(getByRole('region'))
    expect(queryByRole('menu')).toBeNull()
    expect(getByRole('region').textContent).toBe('Rendered children, not the copy source')
  })
  it('retains pending copy after selection closes the menu and ignores an older failed request', async () => {
    let rejectFirst!: (error: Error) => void
    writeText.mockImplementationOnce(() => new Promise((_, reject) => { rejectFirst = reject }))
    const { getByRole, open, queryByRole } = setup()
    fireEvent.click(getByRole('menuitem', { name: /Copy LaTeX/ }))
    expect(queryByRole('menu')).toBeNull()
    open()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    await act(async () => rejectFirst(new Error('Late failure')))
    expect(execCommand).not.toHaveBeenCalled()
    expect(getByRole('status').textContent).toBe('Copied')
  })
  it('restarts feedback expiry for a repeated action', async () => {
    const { getByRole, open } = setup()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    act(() => vi.advanceTimersByTime(1000))
    open()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy LaTeX/ })))
    act(() => vi.advanceTimersByTime(500))
    expect(getByRole('status').textContent).toBe('Copied')
    act(() => vi.advanceTimersByTime(1000))
    expect(getByRole('status').textContent).toBe('')
  })
  it.each(['resolve', 'reject'])('discards pending old-source %s after latex changes', async outcome => {
    let resolve!: () => void
    let reject!: (error: Error) => void
    writeText.mockImplementationOnce(() => new Promise<void>((done, fail) => { resolve = done; reject = fail }))
    const { getByRole, rerender, open, trigger } = setup()
    fireEvent.click(getByRole('menuitem', { name: /Copy math/ }))
    expect(writeText).toHaveBeenCalledWith(source.trim())
    rerender(<Equation latex="new-source"><span>New displayed children</span></Equation>)
    await act(async () => { if (outcome === 'resolve') resolve(); else reject(new Error('Old source denied')) })
    expect(execCommand).not.toHaveBeenCalled()
    expect(getByRole('status').textContent).toBe('')
    expect(document.querySelector('textarea')).toBeNull()
    expect(document.activeElement).toBe(trigger)
    open()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(writeText).toHaveBeenLastCalledWith('new-source')
    expect(getByRole('status').textContent).toBe('Copied')
  })
  it('clears feedback when source changes or copy is removed', async () => {
    const { getByRole, rerender, queryByRole } = setup()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(getByRole('status').textContent).toBe('Copied')
    rerender(<Equation latex="changed"><span>New children</span></Equation>)
    expect(getByRole('status').textContent).toBe('')
    rerender(<Equation><span>Display without copy</span></Equation>)
    expect(queryByRole('button')).toBeNull()
    expect(queryByRole('status')).toBeNull()
    act(() => vi.advanceTimersByTime(1500))
    expect(getByRole('region').textContent).toBe('Display without copy')
  })
  it('reserves the recovery-message footprint beside the menu for every feedback state', async () => {
    const { container, getByRole, open } = setup()
    const reserve = container.querySelector('.equation-feedback-reserve')!
    const status = getByRole('status')
    const controls = container.querySelector('.equation-controls')!
    expect(reserve.getAttribute('aria-hidden')).toBe('true')
    expect(status.parentElement).toBe(reserve.parentElement)
    expect(status.closest('.equation-controls')).toBe(controls)
    expect(status.closest('.action-menu')).toBeNull()
    expect(controls.nextElementSibling?.className).toBe('equation-math')
    expect(controls.hasAttribute('data-pagefind-ignore')).toBe(true)
    expect(reserve.closest('[data-pagefind-ignore]')).toBe(controls)
    expect(container.querySelector('.equation-math')?.closest('[data-pagefind-ignore]')).toBeNull()
    expect(container.querySelector('figcaption')?.closest('[data-pagefind-ignore]')).toBeNull()
    expect(container.querySelector('.action-menu')?.closest('[data-pagefind-ignore]')).toBe(controls)
    const footprint = reserve.textContent
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(status.textContent).toBe('Copied')
    expect(reserve.textContent).toBe(footprint)
    act(() => vi.advanceTimersByTime(1500))
    expect(status.textContent).toBe('')
    writeText.mockRejectedValue(new Error('Denied'))
    execCommand.mockReturnValue(false)
    open()
    await act(async () => fireEvent.click(getByRole('menuitem', { name: /Copy math/ })))
    expect(status.textContent).toBe(footprint)
    expect(status.parentElement).toBe(reserve.parentElement)
    const css = readFileSync('app/editorial.css', 'utf8')
    expect(css).toContain('.equation-feedback-reserve,.equation-copy-status{grid-area:1 / 1}')
    expect(css).toContain('.equation-feedback-reserve{visibility:hidden;pointer-events:none}')
    expect(css).not.toContain('.equation-copy-status:not(:empty)')
  })
  it('does not run fallback for an in-flight action after unmount', async () => {
    let reject!: (error: Error) => void
    writeText.mockImplementation(() => new Promise((_, fail) => { reject = fail }))
    const { getByRole, unmount } = setup()
    fireEvent.click(getByRole('menuitem', { name: /Copy math/ }))
    unmount()
    await act(async () => reject(new Error('Late rejection')))
    expect(execCommand).not.toHaveBeenCalled()
    expect(document.querySelector('textarea')).toBeNull()
  })
})
