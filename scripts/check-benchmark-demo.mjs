import { chromium } from '@playwright/test'

const url = process.argv[2] ?? 'https://4098643f.benebsworth-next.pages.dev/lab/llm-benchmark/3d-physics-animation/n-body-field/'

async function main() {
  const browser = await chromium.launch()
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`))
  page.on('console', (msg) => {
    if (msg.type() === 'error') {
      errors.push(`console.error: ${msg.text()}`)
    }
  })

  await page.goto(url, { waitUntil: 'networkidle' })
  // Pick a model that has live harness output for this task.
  const select = page.locator('select[aria-label="Model for generated demo"]')
  await select.selectOption('kimi-k2.7')
  await page.waitForTimeout(500)
  await page.waitForSelector('iframe[title*="generated by"]', { timeout: 10000 })
  const iframe = page.locator('iframe').first()
  await iframe.waitFor({ state: 'visible' })
  // Give the iframe a moment to execute its inline scripts.
  await page.waitForTimeout(3000)

  const title = await page.title()
  const iframeCount = await page.locator('iframe').count()
  console.log(`Page title: ${title}`)
  console.log(`Iframes found: ${iframeCount}`)
  if (errors.length) {
    console.log('Errors:')
    for (const e of errors) console.log(`  ${e}`)
  } else {
    console.log('No console/page errors detected.')
  }

  await browser.close()
  process.exit(errors.length ? 1 : 0)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
