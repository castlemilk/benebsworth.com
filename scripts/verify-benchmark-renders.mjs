import { chromium } from '@playwright/test'
import { BENCHMARK_TASKS, BENCHMARK_MODELS } from '../lib/lab/llm-benchmark/registry.ts'

const LIVE_MODELS = ['kimi-k2.7', 'kimi-k3', 'gemini-3.5-flash-agy', 'codex-gpt-5.5']
const HTML_CATEGORIES = new Set([
  '3d-physics-animation',
  'advanced-game-building',
  'advanced-physics',
  'advanced-electronics',
  'ui-building',
])
const BASE_URL = process.argv[2] ?? 'https://786514aa.benebsworth-next.pages.dev'

function collectErrors(page) {
  const errors = []
  const onPageError = (e) => errors.push(`pageerror: ${e.message}`)
  const onConsole = (msg) => {
    if (msg.type() === 'error') {
      const text = msg.text()
      if (text && !text.includes('favicon')) errors.push(`console: ${text}`)
    }
  }
  page.on('pageerror', onPageError)
  page.on('console', onConsole)
  return {
    errors,
    detach: () => {
      page.off('pageerror', onPageError)
      page.off('console', onConsole)
    },
  }
}

async function main() {
  const browser = await chromium.launch()
  const failures = []

  for (const task of BENCHMARK_TASKS) {
    const url = `${BASE_URL}/lab/llm-benchmark/${task.category}/${task.slug}/`
    const isHtml = HTML_CATEGORIES.has(task.category)
    console.log(`\n[${task.id}] ${url}`)

    for (const modelId of LIVE_MODELS) {
      const model = BENCHMARK_MODELS.find((m) => m.id === modelId)
      if (!model) continue

      const page = await browser.newPage()
      const { errors, detach } = collectErrors(page)

      try {
        // Skip models that have no captured output for this task (e.g. a
        // provider run blocked by quota) — the page correctly shows its
        // empty state, and that's not a rendering failure.
        const outRes = await page.request.get(
          `${BASE_URL}/lab-data/llm-benchmark/outputs/${task.id}/${modelId}.json`
        )
        const outJson = outRes.ok() ? await outRes.json() : null
        if (!outJson?.output?.trim()) {
          console.log(`  - ${model.name}: no output yet, skipping`)
          continue
        }

        await page.goto(url, { waitUntil: 'networkidle' })

        if (isHtml) {
          await page.locator('select[aria-label="Model for generated demo"]').selectOption(modelId)
          await page.waitForSelector('iframe[title*="generated by"]', { timeout: 20000 })
          await page.waitForTimeout(1500)

          // The standalone full-page artifact must exist whenever the output is
          // a complete HTML document (mirrors the gen script's isFullHtmlDoc
          // gate and the demo's open/download buttons).
          if (/<!doctype\s+html|<html[\s>]/i.test(outJson.output.slice(0, 400))) {
            const htmlRes = await page.request.get(
              `${BASE_URL}/lab-data/llm-benchmark/outputs/${task.id}/${modelId}.html`
            )
            if (!htmlRes.ok()) {
              errors.push(`full-page artifact: HTTP ${htmlRes.status()}`)
            } else {
              const csp = htmlRes.headers()['content-security-policy'] ?? ''
              if (!csp.includes('sandbox')) errors.push('full-page artifact: missing sandbox CSP')
            }
          }
        } else {
          // Text tasks: side-by-side output should show a <pre> with code.
          await page.locator('select[aria-label="Model for generated demo"]').selectOption(modelId)
          await page.waitForTimeout(500)
          await page.waitForSelector('pre code', { timeout: 10000 })
        }

        if (errors.length) {
          failures.push(`${task.id}/${modelId}: ${errors.join('; ')}`)
          console.log(`  ✗ ${model.name}: ${errors.join('; ')}`)
        } else {
          console.log(`  ✓ ${model.name}`)
        }
      } catch (err) {
        failures.push(`${task.id}/${modelId}: ${err instanceof Error ? err.message : String(err)}`)
        console.log(`  ✗ ${model.name}: ${err instanceof Error ? err.message : String(err)}`)
      } finally {
        detach()
        await page.close()
      }
    }

    // Side-by-side outputs (default panes are the first two registry models,
    // which are seeded — the empty-state copy must not appear for them).
    const page = await browser.newPage()
    await page.goto(url, { waitUntil: 'networkidle' })
    const placeholderCount = await page.locator("text=hasn’t been run on this task yet.").count()
    if (placeholderCount > 0) {
      failures.push(`${task.id}: side-by-side has ${placeholderCount} empty output panes`)
      console.log(`  ✗ side-by-side has ${placeholderCount} empty panes`)
    } else {
      console.log(`  ✓ side-by-side outputs populated`)
    }
    await page.close()
  }

  await browser.close()

  if (failures.length) {
    console.log('\nFailures:')
    for (const f of failures) console.log(`  - ${f}`)
    process.exit(1)
  }
  console.log('\nAll benchmark demos and side-by-side outputs render cleanly.')
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
